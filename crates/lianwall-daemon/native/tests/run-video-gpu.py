#!/usr/bin/env python3
"""Opt-in GPU upload/render validation. Never opens a Wayland surface."""
import argparse,json,os,shlex,subprocess,tempfile
from pathlib import Path
parser=argparse.ArgumentParser()
parser.add_argument('--output-dir',type=Path)
parser.add_argument('--validation',action='store_true')
parser.add_argument('--sanitize',action='store_true')
parser.add_argument('--corpus',type=Path,help='directory generated by run-video.py; enables codec/format sweeps')
args=parser.parse_args()
root=Path(__file__).resolve().parent.parent
workspace=tempfile.TemporaryDirectory(prefix='lianwall-video-gpu-') if not args.output_dir else None
out=args.output_dir.resolve() if args.output_dir else Path(workspace.name);out.mkdir(parents=True,exist_ok=True)
summary={'result':'incomplete','mode':'software AVFrame upload to Vulkan','cases':[],'skipped':[],'not_tested':['hardware decoding','zero-copy','actual Wayland presentation']}
env=os.environ.copy()
if args.validation:env['LIANWALL_TEST_VALIDATION']='1'
def run(command,timeout=60):
 r=subprocess.run(list(map(str,command)),env=env,stdout=subprocess.PIPE,stderr=subprocess.PIPE,timeout=timeout)
 if r.returncode:raise RuntimeError(f'{command}\nexit={r.returncode}\n{r.stderr.decode()}\n{r.stdout.decode()}')
 if b'Validation Error' in r.stderr or b'VUID-' in r.stderr or b'runtime error:' in r.stderr:raise RuntimeError(r.stderr.decode())
 return r
try:
 flags=shlex.split(run(['pkg-config','--cflags','--libs','libplacebo','vulkan','libavcodec','libavformat','libavutil']).stdout.decode())
 binary=out/'video-gpu-check';command=[os.environ.get('CC','cc'),'-std=c11','-D_POSIX_C_SOURCE=200809L','-O1','-Wall','-Wextra','-I'+str(root)]
 if os.environ.get('VULKAN_HEADERS'):command+=['-I'+os.environ['VULKAN_HEADERS']]
 if args.sanitize:command+=['-g','-fsanitize=address,undefined','-fno-omit-frame-pointer']
 run(command+[root/'tests/video-gpu.c',root/'video.c',root/'video_gpu.c','-o',binary]+flags+['-lm'])
 yuv=out/'patches.yuv';width,height=96,64
 colors=[(63,102,240),(173,42,26),(32,240,118),(16,128,128),(126,128,128),(235,128,128)]
 planes=[]
 for component in range(3):planes.append(bytes(colors[(y//32)*3+x//32][component] for y in range(height) for x in range(width)))
 yuv.write_bytes(b''.join(planes)*2)
 base=['ffmpeg','-hide_banner','-v','error','-y','-threads','1','-filter_threads','1']
 def encode(name,vf=""):
  path=out/(name+'.mp4')
  run(base+['-f','rawvideo','-pixel_format','yuv444p','-video_size','96x64','-framerate','2','-i',yuv,'-frames:v','2','-c:v','libx264','-threads','1','-crf','0','-pix_fmt','yuv444p','-color_range','tv','-colorspace','bt709','-color_primaries','bt709','-color_trc','iec61966-2-1','-vf','setparams=range=limited:color_primaries=bt709:color_trc=iec61966-2-1:colorspace=bt709'+(','+vf if vf else '')]+[path])
  return path
 patches=encode('patches')
 sar=encode('sar','setsar=2/1')
 rotated=out/'rotated.mp4';run(base+['-display_rotation:v:0','90','-i',patches,'-c','copy',rotated])
 rotation_probe=json.loads(run(['ffprobe','-v','error','-show_streams','-of','json',rotated]).stdout)
 assert any(abs(side.get('rotation',0))==90 for side in rotation_probe['streams'][0].get('side_data_list',[])),rotation_probe
 for path in [patches,sar]:
  probe=json.loads(run(['ffprobe','-v','error','-show_frames','-of','json',path]).stdout)
  assert probe['frames'][0]['color_transfer']=='iec61966-2-1',probe
 for name,path,w,h,fit,vf in [('plain',patches,96,64,1,None),('rotation',rotated,64,96,1,None),('sar',sar,192,64,1,'scale=192:64,setsar=1'),('fit',patches,128,128,1,'scale=128:128:force_original_aspect_ratio=decrease,pad=128:128:(ow-iw)/2:(oh-ih)/2:black'),('crop',patches,128,128,0,'scale=128:128:force_original_aspect_ratio=increase,crop=128:128')]:
  rgba=out/(name+'.rgba');r=run([binary,'pixels',path,rgba,w,h,fit]);(out/(name+'.log')).write_bytes(r.stdout+r.stderr)
  reference=out/(name+'.reference.rgba');command=base+['-i',path,'-frames:v','1']
  if vf:command+=['-vf',vf]
  run(command+['-pix_fmt','rgba','-f','rawvideo',reference])
  actual=rgba.read_bytes();expected=reference.read_bytes();assert len(actual)==len(expected)==w*h*4
  # Flat interior patch samples avoid differences between scaler edge kernels.
  differences=[]
  for y in range(8,h-8,8):
   for x in range(8,w-8,8):
    offset=(y*w+x)*4
    # Ignore reference edges (incl. rounded fit border) where interpolation is expected.
    neighbors=[expected[((y+dy)*w+x+dx)*4:((y+dy)*w+x+dx)*4+3] for dx,dy in [(-3,0),(3,0),(0,-3),(0,3)]]
    if any(max(abs(expected[offset+c]-n[c]) for c in range(3))>5 for n in neighbors):continue
    differences.extend(abs(actual[offset+c]-expected[offset+c]) for c in range(4))
  assert differences and max(differences)<=4,(name,max(differences) if differences else None,r.stdout.decode())
  case={'case':name,'max_flat_pixel_delta':max(differences),'result':'pass'};summary['cases'].append(case);print(json.dumps(case),flush=True)
 # Exercise plane reuse/recreation and held frame lifetime on prior CPU corpus.
 corpus=args.corpus.resolve() if args.corpus else None
 for name in ['cfr-bframes.mp4','vfr-bframes.mp4','high10.mp4','resolution-change.h264','pixel-format-change.h264','hevc.mp4','vp9.webm','av1.mkv']:
  if corpus is None:
   summary['skipped'].append(name)
   continue
  path=corpus/name
  if not path.is_file():raise RuntimeError(f'missing corpus fixture: {path}')
  r=run([binary,'sweep',path]);(out/(name+'.gpu.log')).write_bytes(r.stdout+r.stderr)
  summary['cases'].append({'case':name,'result':'pass'});print(r.stdout.decode().strip(),flush=True)
 summary['result']='pass'
finally:
 (out/'summary.json').write_text(json.dumps(summary,indent=2)+'\n')
 if not workspace:print('results:',out,flush=True)
 if workspace:workspace.cleanup()
